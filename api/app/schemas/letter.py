from datetime import date, datetime
from decimal import Decimal
from typing import Any

from pydantic import BaseModel, ConfigDict


class LetterChecks(BaseModel):
    """Result of the post-generation checks (CLAUDE.md: flag, don't auto-fix)."""

    issues: list[str] = []  # blocking: body was not accepted
    warnings: list[str] = []  # non-blocking: shown to staff
    attempts: int = 0
    tool_calls: list[str] = []  # MCP tools the agent used, in order


class LetterNote(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    note_id: int
    donor_id: int
    gift_id: int | None
    batch_week: date
    body: str | None
    status: str
    approved_by: str | None
    sent_at: datetime | None
    created_at: datetime
    share_token: str | None
    badge_key: str | None
    impact_key: str | None
    llm_model: str | None
    checks: dict[str, Any] | None


class LetterGift(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    gift_id: int
    gift_date: date
    amount: Decimal
    fund: str | None
    campaign: str | None
    receipt_note: str | None


class LetterDonor(BaseModel):
    donor_id: int
    first_name: str
    last_name: str
    address_line: str | None
    city: str | None
    state: str | None
    zip: str | None


class LetterBadge(BaseModel):
    key: str
    title: str
    meaning: str


class LetterResponse(BaseModel):
    """The letter for one donor, as shown on the donor's letter page."""

    note: LetterNote
    gift: LetterGift
    donor: LetterDonor
    badge: LetterBadge | None
    impact_text: str | None
    share_url: str | None
    qr_url: str | None
    created: bool  # a new note row was created by this call
    generated: bool  # the body was (re)generated by this call
    needs_attention: bool  # no accepted body: staff must look at `note.checks`
    warnings: list[str]


class PublicLetter(BaseModel):
    """What the private token page shows. Never includes amounts or gift details."""

    first_name: str
    badge: LetterBadge | None
    greeting: str | None
    impact_text: str | None
    closing: str | None
    status: str
    donate_link: str
